import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { readChain, CHAIN_FILE, ARTIFACTS_DIR } from './chain.mjs';
import { sha256File, VERSION } from './util.mjs';

export async function buildBundle(cwd, captureId, outDir) {
  const records = await readChain(cwd);
  const capture = records.find((r) => r.id === captureId && r.type === 'capture');
  if (!capture) throw new Error(`capture not found: ${captureId}`);
  const replays = records.filter((r) => r.type === 'replay' && r.payload.ref === captureId);
  const anchors = records.filter((r) => r.type === 'anchor');

  const captureIndex = records.indexOf(capture);
  const nextRecord = records[captureIndex + 1];
  const headAfter = nextRecord ? nextRecord.hash : capture.hash;

  const out = path.resolve(cwd, outDir || `evidence-${captureId}`);
  await mkdir(out, { recursive: true });

  const files = [];
  await copyFile(path.join(cwd, CHAIN_FILE), path.join(out, 'chain.jsonl'));
  files.push({ path: 'chain.jsonl', sha256: await sha256File(path.join(out, 'chain.jsonl')) });

  for (const name of [`${captureId}.stdout.txt`, `${captureId}.stderr.txt`]) {
    try {
      await copyFile(path.join(cwd, ARTIFACTS_DIR, name), path.join(out, name));
      files.push({ path: name, sha256: await sha256File(path.join(out, name)) });
    } catch {
      // artifact missing — skip
    }
  }

  const manifest = {
    tool: 'poc-evidence',
    version: VERSION,
    captureId,
    generatedAt: new Date().toISOString(),
    capture,
    replays,
    anchors,
    headAfter,
    files,
  };
  await writeFile(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2), 'utf8');
  await writeFile(path.join(out, 'REPORT.md'), renderReport(manifest), 'utf8');
  await writeFile(path.join(out, 'VERIFY.txt'), renderVerify(manifest), 'utf8');
  return { out, manifest };
}

function renderReport(m) {
  const c = m.capture;
  const p = c.payload;
  const fileRows = (list) => list.map((f) => `| \`${f.path}\` | \`${f.sha256}\` |`).join('\n');
  const replayRows = m.replays.length
    ? m.replays.map((r) => `| ${r.id} | ${r.ts} | **${r.payload.verdict}** |`).join('\n')
    : '| — | — | none yet |';
  const anchorRows = m.anchors.length
    ? m.anchors.map((r) => `| ${r.ts} | \`${r.payload.head.slice(0, 16)}…\` | ${r.payload.message ?? ''} |`).join('\n')
    : '| — | none yet | |';
  const normList = p.normalizers.length
    ? p.normalizers.map((n) => `- pattern \`${n.pattern}\` (flags \`${n.flags}\`) => \`${n.replacement}\``).join('\n')
    : '- none';
  const redactList = p.redactions.length
    ? p.redactions.map((n) => `- pattern \`${n.pattern}\` (flags \`${n.flags}\`) => \`[REDACTED]\``).join('\n')
    : '- none';

  return `# PoC Evidence — ${c.id}
${p.label ? `\n**Label:** ${p.label}\n` : ''}
Generated by poc-evidence v${m.version} at ${m.generatedAt}. All digests are SHA-256.

## Command

\`\`\`sh
${p.command.join(' ')}
\`\`\`

- Working directory: \`${p.cwd}\`
- Platform: ${p.runtime.platform} (${p.runtime.arch}), node ${p.runtime.node}
- Exit code: **${p.exitCode}** after ${p.durationMs} ms

## Output digests (after redaction + normalization)

| Stream | SHA-256 |
|---|---|
| stdout (${p.stdoutBytes} bytes) | \`${p.stdoutHash}\` |
| stderr (${p.stderrBytes} bytes) | \`${p.stderrHash}\` |

## Input files (${p.inputFiles.length})

| Path | SHA-256 |
|---|---|
${p.inputFiles.length ? fileRows(p.inputFiles) : '| — | |'}

## Output files (${p.outputFiles.length})

| Path | SHA-256 |
|---|---|
${p.outputFiles.length ? fileRows(p.outputFiles) : '| — | |'}

## Determinism

| Replay | At | Verdict |
|---|---|---|
${replayRows}

Normalization rules applied before hashing:
${normList}

Redaction rules applied before storing:
${redactList}

## Integrity

- Capture record hash: \`${c.hash}\`
- Chain head after capture: \`${m.headAfter}\`
- Environment: recorded as ${p.envMode === 'values' ? '**values** (captured with --env-values)' : 'SHA-256 hashes (values never stored)'}

| Anchor | Head | Note |
|---|---|---|
${anchorRows}

## Scope & limits (read before relying on this)

This bundle does NOT prove when the vulnerability was discovered — only when
each record was hashed. It also does NOT prove that outputs were not crafted
before capture by a malicious wrapper: poc-evidence attests what the recorded
command produced, not how that command came to exist.

## Verify

See \`VERIFY.txt\` in this bundle. Bundle file digests are listed in \`manifest.json\`.
`;
}

function renderVerify(m) {
  const fileList = m.files.map((f) => `  ${f.path}  ${f.sha256}`).join('\n');
  return `Verifying this poc-evidence bundle
====================================

1) File digests (no extra tooling required)

   Linux/macOS:  sha256sum <file>      (or: shasum -a 256 <file>)
   Windows:      certutil -hashfile <file> SHA256

   Expected digests:
${fileList}

   These must match the files in this bundle exactly, and the "files" array
   in manifest.json must match this list.

2) Chain integrity (requires poc-evidence)

   In an empty directory:
     mkdir .poc-evidence
     cp chain.jsonl .poc-evidence/chain.jsonl
     poc-evidence verify

   This recomputes every record hash and verifies each record links to the
   previous one. Any edit after the fact breaks the chain.

3) Reproduction

   Restore the input files (digests in REPORT.md), run the command from
   REPORT.md in the recorded working directory, then compare exit code and
   output digests. With poc-evidence, keep .poc-evidence/chain.jsonl in the
   tree and run:
     poc-evidence replay ${m.captureId}

   Remember: digests cover redacted + normalized output. Apply the rules
   listed in REPORT.md (and manifest.json) before comparing.

What this proves
----------------
- The recorded command produced exactly the recorded digests at capture time.
- The evidence chain has not been edited since each record was appended.
- Git anchors (if any) bind chain heads to commits; pushing those commits to
  a remote produces a third-party timestamp of the anchored state.

What it does NOT prove
----------------------
- When the vulnerability was discovered (only when the evidence was hashed).
- That outputs were not crafted before capture by a malicious wrapper.
`;
}
